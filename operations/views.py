"""
WEEK 9 — Lab C. CRUD for one business object, with class-based views.

Each view is a class Django already wrote: it knows how to do one job (list, show, create,
update, delete). We fill in the blanks: which model, which form, which template, where to go next.

LoginRequiredMixin, first in every class: the back office is for staff. A visitor who is not
logged in is sent to /accounts/login/ instead of seeing — or changing — a single customer.
"""

from django.contrib import messages
from django.contrib.auth.mixins import LoginRequiredMixin
from django.db.models import Count, Max
from django.db.models.deletion import ProtectedError
from django.shortcuts import redirect
from django.urls import reverse_lazy
from django.utils import timezone
from django.views.generic import CreateView, DeleteView, DetailView, ListView, UpdateView

from .forms import CustomerForm
from .models import Customer


class CustomerListView(LoginRequiredMixin, ListView):        # R — many
    model = Customer
    template_name = "operations/customer_list.html"
    context_object_name = "customers"
    paginate_by = 25

    def get_queryset(self):
        qs = Customer.objects.annotate(order_count=Count("orders")).order_by("customer_name")
        q = self.request.GET.get("q", "").strip()
        if q:
            qs = qs.filter(customer_name__icontains=q)       # ?q=grind → WHERE customer_name ILIKE '%grind%'
        return qs


class CustomerDetailView(LoginRequiredMixin, DetailView):    # R — one
    model = Customer
    template_name = "operations/customer_detail.html"
    context_object_name = "customer"


class CustomerCreateView(LoginRequiredMixin, CreateView):    # C
    model = Customer
    form_class = CustomerForm
    template_name = "operations/customer_form.html"

    def form_valid(self, form):
        # customer_id is a plain INTEGER key (the spreadsheet's numbers), not generated by the
        # database, so the application picks the next one. Two clerks saving at the same moment
        # could pick the same number: that is Week 10's problem (transactions).
        top = Customer.objects.aggregate(m=Max("customer_id"))["m"] or 0
        form.instance.customer_id = top + 1
        form.instance.customer_since = timezone.localdate()
        messages.success(self.request, f"Customer {form.instance.customer_name} created.")
        return super().form_valid(form)

    def get_success_url(self):
        return reverse_lazy("customer_detail", args=[self.object.pk])


class CustomerUpdateView(LoginRequiredMixin, UpdateView):    # U
    model = Customer
    form_class = CustomerForm
    template_name = "operations/customer_form.html"

    def form_valid(self, form):
        messages.success(self.request, "Changes saved.")
        return super().form_valid(form)

    def get_success_url(self):
        return reverse_lazy("customer_detail", args=[self.object.pk])


class CustomerDeleteView(LoginRequiredMixin, DeleteView):    # D
    model = Customer
    template_name = "operations/customer_confirm_delete.html"
    success_url = reverse_lazy("customer_list")

    def form_valid(self, form):
        try:
            return super().form_valid(form)
        except ProtectedError:
            # on_delete=PROTECT: a customer with orders cannot be deleted. The database would
            # refuse too (REFERENCES with no ON DELETE); Django refuses first, readably.
            messages.error(self.request, f"{self.object} has orders, so it cannot be deleted.")
            return redirect("customer_detail", pk=self.object.pk)
